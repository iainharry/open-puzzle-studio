/**
 * Writes `dist/sw.js` after the Vite build.
 *
 * Hand-written rather than a plugin, for the reason recorded in the jigsaw project: a
 * service worker is forty lines of cache logic and a generated one is forty lines you did
 * not read, in a dependency you now own.
 *
 * Navigations are network-first so a new build is picked up on the next visit; hashed
 * assets are cache-first because their names change when they do.
 */

import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(relative(DIST, full).split('\\').join('/'));
  }
  return out;
}

const files = (await walk(DIST)).filter((f) => f !== 'sw.js' && !f.endsWith('.map'));
const hash = createHash('sha256');
for (const file of files.sort()) {
  hash.update(file);
  hash.update(await readFile(join(DIST, file)));
}
const build = hash.digest('hex').slice(0, 12);

const sw = `/* Generated by scripts/build-sw.mjs. Do not edit. */
const CACHE = 'ops-${build}';
const ASSETS = ${JSON.stringify(files.map((f) => `./${f}`), null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  // Network-first for navigations, so a new build is picked up rather than a stale index
  // being served out of the cache forever.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() => caches.match('./index.html').then((r) => r ?? Response.error())),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((hit) => hit ?? fetch(request)),
  );
});
`;

await writeFile(join(DIST, 'sw.js'), sw);
console.log(`sw.js written — build ${build}, ${files.length} assets precached`);
